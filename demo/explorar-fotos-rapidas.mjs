import { chromium } from '@playwright/test'
const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] })
const ctx = await b.newContext({ viewport: { width: 1366, height: 768 }, permissions: ['camera'] })
const p = await ctx.newPage()
p.on('pageerror', e => console.log('PAGEERROR', String(e).slice(0, 300)))
await p.goto('http://localhost:5174/app/login', { timeout: 150000, waitUntil: 'domcontentloaded' })
await p.locator('#pf-email').waitFor({ timeout: 150000 })
await p.locator('#pf-email').fill('p@g.com'); await p.locator('#pf-pass').fill('123456')
await p.getByRole('button', { name: 'Iniciar sesión' }).click()
await p.locator('header').waitFor({ timeout: 90000 }); await p.waitForTimeout(2500)
const sel = p.locator('header select'); if (await sel.count()) await sel.selectOption({ label: 'Chalco' }).catch(() => {})
await p.goto('http://localhost:5174/app/pacientes/e1d99257-2862-4120-878a-c62786048510', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(4000)
await p.getByRole('tab', { name: /Fotos clínicas/ }).click(); await p.waitForTimeout(2500)
await p.getByRole('button', { name: /Foto rápida/ }).click(); await p.waitForTimeout(3500)
await p.screenshot({ path: process.env.TEMP + '/fr1.png' })
for (let i = 0; i < 2; i++) { await p.getByRole('button', { name: /Tomar foto/ }).click(); await p.waitForTimeout(4500) }
console.log('MODAL:', (await p.locator('.modal, [role=dialog]').first().innerText()).replace(/\n+/g, ' | ').slice(0, 400))
await p.screenshot({ path: process.env.TEMP + '/fr2.png' })
await p.getByRole('button', { name: /Terminar/ }).click(); await p.waitForTimeout(4000)
await p.screenshot({ path: process.env.TEMP + '/fr3.png' })
console.log('EVOL:', (await p.locator('[aria-label="Evolución por zona"]').innerText().catch(() => 'sin evolución')).replace(/\n+/g, ' | ').slice(0, 400))
await b.close()
