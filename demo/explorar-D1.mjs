import { chromium } from '@playwright/test'
const b = await chromium.launch({ channel: 'chrome', headless: true })
const p = await b.newPage({ viewport: { width: 1366, height: 768 } })
const T = process.env.TEMP
await p.goto('http://localhost:5174/app/reservar/pie-clinic-sintetico', { timeout: 150000, waitUntil: 'domcontentloaded' })
await p.waitForTimeout(6000)
await p.screenshot({ path: T + '/d1_a.png' })
console.log((await p.locator('body').innerText()).slice(0, 1500))
await p.getByRole('button', { name: /^Centenario/ }).first().click()
await p.waitForTimeout(1500)
console.log('---SERV\n' + (await p.locator('body').innerText()).slice(0, 1500))
await p.getByRole('button', { name: /Quiropodia/ }).first().click()
await p.waitForTimeout(1500)
console.log('---POD\n' + (await p.locator('body').innerText()).slice(0, 1200))
await p.getByRole('button', { name: /Podólogo\(a\) 2/ }).first().click().catch(()=>{})
await p.waitForTimeout(3500)
await p.screenshot({ path: T + '/d1_b.png' })
console.log('---HOR\n' + (await p.locator('body').innerText()).slice(0, 1500))
await b.close()
