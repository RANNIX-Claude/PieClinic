// Video VID-F2: catálogo y precios (alta de servicio y producto, precio por sucursal con vigencia, «Admite características») y pantalla «Características y adaptaciones».
// Correr: PW_LOTE=F BASE_URL=http://localhost:5174 npx playwright test -c playwright.caja.config.ts vid-catalogo-precios
import { test, expect } from '@playwright/test'
import { crearVideo, letras, escribir } from './lib/video'

const SEDE = 'Pie Clinic Centenario'
const v = crearVideo('catalogo-precios')
const marca = Date.now().toString(36).slice(-4).toUpperCase()
const COD = `SV-V${marca}`, SKU = `PF-V${marca}`
const NOM_SERV = `Plantilla deportiva a la medida ${marca}`, NOM_PROD = `Plantilla de gel para talón ${marca}`
const futuro = (d: number) => { const x = new Date(); x.setDate(x.getDate() + d); return x.toISOString().slice(0, 10) }

test('Catálogo y precios: servicio, producto, precio por sucursal y características', async ({ page, context }) => {
  await v.empezar(context)
  await v.firmar(page, SEDE, 'Prueba del catálogo y de los precios de Pie Clinic. Caso: dar de alta un servicio y un producto, ponerles precio con vigencia y por sucursal, marcar que un servicio admite características, y revisar la pantalla de características y adaptaciones.', 'm@g.com', 'la persona administradora')
  await v.irA(page, /Catálogo y precios/)
  await expect(page.getByRole('button', { name: /Nuevo servicio/ })).toBeVisible({ timeout: 30_000 })
  await v.narrar(page, 'Este es el catálogo. Arriba hay indicadores de servicios y productos activos, y pestañas para servicios, productos, histórico de precios e importación de listas. Solo el administrador puede editar el catálogo.')

  // 1. Servicio nuevo
  await v.narrar(page, 'Se da de alta un servicio nuevo.', 0)
  await page.getByRole('button', { name: /Nuevo servicio/ }).click()
  const m = page.getByRole('dialog').last()
  await expect(m).toBeVisible()
  await escribir(m.getByLabel('Código', { exact: true }), COD)
  await m.getByLabel('Categoría', { exact: true }).fill('Biomecánica')
  await escribir(m.getByLabel('Nombre canónico'), NOM_SERV)
  await m.getByLabel('Desde', { exact: true }).check()
  await m.getByLabel('Duración (min)').fill('45')
  await m.getByLabel('IVA', { exact: true }).selectOption({ label: '16 %' })
  await v.narrar(page, `El código es ${COD.replace(/-/g, ' ')} y el nombre, ${NOM_SERV}. El tipo de precio es Desde, porque el precio base se cotiza según el caso. Dura cuarenta y cinco minutos y lleva I V A de dieciséis por ciento.`, 0)
  await m.getByLabel('Admite características (producto especial a la medida)').check()
  await m.getByLabel('Precio por sucursal', { exact: true }).check()
  await v.narrar(page, 'Se marca Admite características, para que en caja se puedan elegir material, altura y adaptaciones, y también Precio por sucursal, para poder fijar precios distintos por clínica.', 0)
  await m.getByRole('button', { name: /Guardar servicio/ }).click()
  await expect(m.getByText('Nuevo precio')).toBeVisible({ timeout: 30_000 })
  await v.narrar(page, 'Al guardar, el servicio se crea y aparece el panel de precio a la derecha.')

  // 2. Precio de lista
  await m.getByLabel('Nuevo precio').fill('1500')
  await m.getByLabel('Motivo', { exact: true }).selectOption({ label: 'Alta inicial' })
  await v.narrar(page, 'Primero el precio de lista, para todas las sucursales: mil quinientos pesos, con I V A incluido, vigente desde hoy.', 0)
  await m.getByRole('button', { name: /Guardar cambio de precio/ }).click()
  await expect(m.locator('tbody tr', { hasText: 'Todas (lista)' }).first()).toBeVisible({ timeout: 30_000 })
  await page.waitForTimeout(1500)

  // 3. Precio por sucursal
  await m.getByLabel('Sucursal', { exact: true }).selectOption({ label: SEDE })
  await m.getByLabel('Nuevo precio').fill('1650')
  await m.getByLabel('Motivo', { exact: true }).selectOption({ label: 'Precio por sede' })
  await v.narrar(page, `Ahora un precio propio para ${SEDE}: mil seiscientos cincuenta pesos. Las sucursales sin precio propio heredan el de lista.`, 0)
  await m.getByRole('button', { name: /Guardar cambio de precio/ }).click()
  await expect(m.locator('tbody tr', { hasText: SEDE })).toHaveCount(1, { timeout: 30_000 })
  await page.waitForTimeout(1500)

  // 4. Cambio programado con vigencia
  const fut = futuro(30)
  await m.getByLabel('Sucursal', { exact: true }).selectOption({ label: SEDE })
  await m.getByLabel('Nuevo precio').fill('1750')
  await m.getByLabel('Vigente desde', { exact: true }).fill(fut)
  await m.getByLabel('Motivo', { exact: true }).selectOption({ label: 'Inflación' })
  await v.narrar(page, 'También se puede programar un cambio futuro: en treinta días el precio de esa sucursal sube a mil setecientos cincuenta. El precio actual no se pierde: el sistema cierra su vigencia y guarda la nueva versión.', 0)
  await m.getByRole('button', { name: /Programar cambio futuro/ }).click()
  await expect(m.locator('tbody tr', { hasText: SEDE })).toHaveCount(3, { timeout: 30_000 }).catch(() => {})
  await page.waitForTimeout(2000)
  const versiones = (await m.locator('tbody tr').allInnerTexts()).map(t => t.replace(/\s+/g, ' '))
  expect(versiones.join('|')).toMatch(/programado/i)
  await v.narrar(page, 'La tabla de versiones muestra los tres precios: el de lista, el de la sucursal vigente hoy, y el programado a futuro.')
  await m.getByRole('button', { name: 'Cerrar' }).first().click()
  await page.waitForTimeout(1500)

  // 5. Se ve en el listado
  await page.getByLabel(/Solo con precio por sucursal/).check()
  await page.waitForTimeout(1500)
  const filaS = page.locator('tbody tr', { hasText: NOM_SERV }).first()
  await filaS.scrollIntoViewIfNeeded()
  await expect(filaS).toBeVisible({ timeout: 30_000 })
  const txtS = (await filaS.innerText()).replace(/\s+/g, ' ')
  expect(txtS).toMatch(/Desde/)
  await v.narrar(page, 'En el listado de servicios aparece el nuevo, con tipo de precio Desde, su precio vigente de lista y la columna de precio por sucursal en Sí. Con este filtro solo se ven los servicios que tienen precios distintos por sucursal.')
  await page.getByLabel(/Solo con precio por sucursal/).uncheck()
  await filaS.getByRole('button', { name: 'Historial' }).click().catch(() => {})
  const hm = page.getByRole('dialog').last()
  if (await hm.isVisible().catch(() => false)) {
    await page.waitForTimeout(2000)
    await v.narrar(page, 'El historial guarda cada versión con su vigencia, la sucursal, el motivo y quién la cambió. Nada se sobrescribe.')
    await hm.getByRole('button', { name: 'Cerrar' }).first().click()
  }

  // 6. Producto
  await v.narrar(page, 'Ahora un producto. Se pulsa Nuevo producto.', 0)
  await page.getByRole('button', { name: /Nuevo producto/ }).click()
  const mp = page.getByRole('dialog').last()
  await escribir(mp.getByLabel('SKU', { exact: true }), SKU)
  await mp.getByLabel('Categoría', { exact: true }).fill('Cuidado en casa')
  await escribir(mp.getByLabel('Nombre canónico'), NOM_PROD)
  await mp.getByLabel('Marca', { exact: true }).fill('Pie Clinic')
  await mp.getByLabel('IVA', { exact: true }).selectOption({ label: '16 %' })
  await v.narrar(page, `El producto lleva su S K U, ${SKU.replace(/-/g, ' ')}, nombre, marca e I V A. A diferencia del servicio, un producto también puede manejar lote y caducidad.`, 0)
  await mp.getByRole('button', { name: /Guardar producto/ }).click()
  await expect(mp.getByText('Nuevo precio')).toBeVisible({ timeout: 30_000 })
  await mp.getByLabel('Nuevo precio').fill('180')
  await mp.getByLabel('Motivo', { exact: true }).selectOption({ label: 'Alta inicial' })
  await v.narrar(page, 'Se guarda y se define su precio de venta: ciento ochenta pesos con I V A incluido.', 0)
  await mp.getByRole('button', { name: /Guardar cambio de precio/ }).click()
  await page.waitForTimeout(2500)
  await mp.getByRole('button', { name: 'Cerrar' }).first().click()
  await page.getByRole('tab', { name: 'Productos' }).click()
  await page.waitForTimeout(2000)
  const filaP = page.locator('tbody tr', { hasText: NOM_PROD }).first()
  await filaP.scrollIntoViewIfNeeded()
  await expect(filaP).toBeVisible({ timeout: 30_000 })
  const txtP = (await filaP.innerText()).replace(/\s+/g, ' ')
  expect(txtP).toMatch(/180/)
  await v.narrar(page, 'En la pestaña de productos aparece el nuevo, con su precio de venta, su costo, su margen y la existencia, que empieza en cero hasta que se registre una compra.')

  // 7. Características y adaptaciones
  await v.irA(page, /Características y adaptaciones/)
  await expect(page.getByRole('heading', { name: /Características y adaptaciones/ }).first()).toBeVisible({ timeout: 30_000 })
  await page.waitForTimeout(2500)
  const base = await page.locator('tbody tr').count()
  expect(base).toBeGreaterThan(3)
  await v.narrar(page, `Esta es la pantalla de características y adaptaciones. Un producto especial a la medida es un servicio con Admite características, como el que se acaba de crear. Aquí está el catálogo de lo que se puede elegir en caja: ${base} características, agrupadas por material, altura, adaptación y lado, cada una con la frase que sale en el ticket y el precio que suma.`)
  await page.getByRole('button', { name: /Nueva característica/ }).click()
  const mc = page.getByRole('dialog').last()
  await mc.getByLabel('Grupo').fill('Adaptación')
  await mc.getByLabel('Nombre', { exact: true }).fill(`Barra retrocapital ${marca}`)
  await mc.getByLabel('Frase para la descripción').fill('con barra retrocapital')
  await mc.getByLabel('Efecto en el precio').selectOption({ label: 'Suma un monto fijo' })
  await mc.getByLabel(/Monto/).fill('250')
  await v.narrar(page, 'Se crea una característica nueva: una barra retrocapital, del grupo Adaptación. Define la frase que se imprime, con barra retrocapital, y que suma doscientos cincuenta pesos fijos.', 0)
  await mc.getByRole('button', { name: 'Guardar' }).click()
  const filaC = page.locator('tbody tr', { hasText: `Barra retrocapital ${marca}` }).first()
  await filaC.scrollIntoViewIfNeeded()
  await expect(filaC).toBeVisible({ timeout: 30_000 })
  await v.narrar(page, 'Queda en el catálogo y desde ese momento aparece como opción en caja para los productos especiales.')

  // 8. En caja el servicio nuevo ofrece las características
  await v.irA(page, /Caja y tickets/)
  await page.waitForTimeout(3000)
  await expect(page.locator('.cj-buscar-in')).toBeVisible({ timeout: 30_000 })
  await page.keyboard.press('F2')
  await escribir(page.locator('.cj-buscar-in'), 'plantilla depor')
  await page.waitForTimeout(1500)
  await page.locator('.cj-res button', { hasText: NOM_SERV }).first().click()
  await page.waitForTimeout(1500)
  const lin = page.locator('.cj-linea', { hasText: NOM_SERV })
  await expect(lin.locator('.cj-carac')).toBeVisible({ timeout: 20_000 })
  const optBarra = lin.getByLabel('Característica', { exact: true }).locator('option', { hasText: `Barra retrocapital ${marca}` })
  await expect(optBarra).toHaveCount(1)
  await v.narrar(page, 'Para comprobarlo, en caja se busca el servicio nuevo. El renglón muestra el panel para cotizar el precio base y elegir características, y la barra retrocapital recién creada ya está entre las opciones.', 0)
  await page.waitForTimeout(1500)
  await v.narrar(page, 'Así se administra el catálogo: servicios y productos con precio por vigencia y por sucursal, y las características de los productos a la medida. Fin del caso.')
  await v.terminar(page, { COD, SKU, NOM_SERV, NOM_PROD, fut, versiones, txtS, txtP, base })
})
