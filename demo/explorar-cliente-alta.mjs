import { chromium } from '@playwright/test'
const b = await chromium.launch({ channel: 'chrome', headless: true })
const p = await (await b.newContext({ viewport: { width: 1366, height: 768 } })).newPage()
p.on('pageerror', e => console.log('PAGEERROR', String(e).slice(0, 300)))
await p.goto('http://localhost:5174/app/login', { timeout: 150000, waitUntil: 'domcontentloaded' })
await p.locator('#pf-email').waitFor({ timeout: 150000 })
await p.locator('#pf-email').fill('r@g.com'); await p.locator('#pf-pass').fill('123456')
await p.getByRole('button', { name: 'Iniciar sesión' }).click()
await p.locator('header').waitFor({ timeout: 90000 }); await p.waitForTimeout(2500)
await p.locator('header select').selectOption({ label: 'Pie Clinic Centenario' }); await p.waitForTimeout(1500)
await p.getByRole('link', { name: /Caja y tickets/ }).first().click(); await p.waitForTimeout(5000)
await p.locator('.cj-tile', { hasText: 'Paciente' }).click(); await p.waitForTimeout(1000)
await p.getByPlaceholder(/Buscar cliente/).pressSequentially('Zorayda Prueba', { delay: 60 }); await p.waitForTimeout(2500)
await p.getByRole('button', { name: /Nuevo cliente/ }).click(); await p.waitForTimeout(800)
await p.getByLabel('Teléfono del cliente').fill('5555550101')
await p.screenshot({ path: process.env.TEMP + '/cli-alta1.png' })
await p.getByRole('button', { name: /Guardar cliente y usarlo/ }).click(); await p.waitForTimeout(3000)
console.log('PANEL:', (await p.locator('.cj-panel').innerText()).replace(/\n+/g, ' | ').slice(0, 300))
await p.getByRole('link', { name: 'Clientes' }).first().click().catch(() => {})
await p.goto('http://localhost:5174/app/clientes', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(3500)
await p.getByLabel('Buscar cliente').fill('Zorayda'); await p.waitForTimeout(2500)
await p.screenshot({ path: process.env.TEMP + '/cli-alta2.png' })
await p.locator('tbody tr').first().click(); await p.waitForTimeout(4000)
console.log('HIST:', (await p.locator('.pagina').innerText()).replace(/\n+/g, ' | ').slice(0, 260))
await p.getByRole('button', { name: /Dar de alta como paciente/ }).click(); await p.waitForTimeout(5000)
console.log('URL:', p.url())
await p.screenshot({ path: process.env.TEMP + '/cli-alta3.png' })
await b.close()
