// Video VID-D3: portal del paciente con la liga personal. La clínica agenda una cita y genera la liga; la paciente (sin cuenta) confirma
// y reprograma su cita; después entra a la sala de la videoconsulta (el proveedor de video es simulado). Lote D.
// Requiere telemedicina activa en la organización de QA (P-147, apagada por defecto): ver hallazgos_D.md.
// Correr: PW_LOTE=D BASE_URL=http://localhost:5184 npx playwright test -c playwright.caja.config.ts vid-portal-cita
import { test, expect } from '@playwright/test'
import { crearVideo } from './lib/video'

const SEDE = 'Centenario'
const v = crearVideo('vid-portal-cita')
const iso = (d: Date) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
const largo = (d: string) => new Date(d + 'T12:00').toLocaleDateString('es-MX', { weekday: 'long', day: 'numeric', month: 'long' })
// cámara y micrófono simulados del propio navegador: el "video" de la prueba es una imagen sintética
test.use({ launchOptions: { slowMo: 250, args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] }, permissions: ['camera', 'microphone'] })

async function agendar(page: any, busqueda: string, servicio: string, fecha: string | null, videoconsulta = false, hora?: string) {
  await page.getByRole('button', { name: /Nueva cita/ }).click()
  await expect(page.getByRole('heading', { name: 'Datos de la cita' })).toBeVisible({ timeout: 30_000 })
  await page.getByPlaceholder(/Buscar paciente/).pressSequentially(busqueda, { delay: 120 })
  const op = page.locator('button', { hasText: /· .*·/ }).filter({ has: page.locator('b') }).first()
  await expect(op).toBeVisible({ timeout: 30_000 })
  const nombre = (await op.locator('b').innerText()).trim()
  await page.waitForTimeout(1000)
  await op.click()
  await page.getByLabel('Servicio', { exact: true }).selectOption({ label: servicio })
  const pod = page.getByLabel('Podólogo', { exact: true })
  const ops = await pod.locator('option').allInnerTexts()
  await pod.selectOption({ index: ops.findIndex((t: string, i: number) => i > 0 && /Paulina Soto/.test(t)) })
  if (videoconsulta) await page.getByLabel('Videoconsulta').check()
  return nombre
}

test('Portal del paciente: confirmar, reprogramar y sala de videoconsulta', async ({ page, context }) => {
  test.setTimeout(25 * 60_000)
  await v.empezar(context)
  await v.firmar(page, SEDE, 'Prueba del portal del paciente de Pie Clinic. Caso: la clínica agenda una cita y genera la liga personal; la paciente, sin cuenta, confirma y reprograma su cita desde esa liga, y después entra a la sala de su videoconsulta.', 'm@g.com', 'la persona administradora')
  await v.irA(page, /^Agenda$/)

  // ───────── Parte A: liga personal ─────────
  await v.narrar(page, 'Primero, la clínica agenda una cita. Se pulsa Nueva cita.', 0)
  const nombre = await agendar(page, 'jime', 'Quiropodia · 30 min', null)
  let hay = 0, fecha = ''
  for (let d = 5; d <= 12 && !hay; d++) {
    const f = new Date(); f.setDate(f.getDate() + d); if (f.getDay() === 0) continue
    fecha = iso(f)
    await page.getByLabel('Fecha', { exact: true }).fill(fecha)
    await page.waitForTimeout(2500)
    hay = await page.locator('h3', { hasText: 'Disponibilidad' }).locator('xpath=following-sibling::div[1]//button').count()
  }
  const slot = page.locator('h3', { hasText: 'Disponibilidad' }).locator('xpath=following-sibling::div[1]//button').nth(2)
  const hora = (await slot.innerText()).trim()
  await slot.click()
  await page.waitForTimeout(1000)
  await v.narrar(page, `Se agenda a ${nombre} para una quiropodia con Paulina Soto el ${largo(fecha)} a las ${hora}. Queda marcada la casilla que pide confirmación de asistencia con liga.`, 0)
  await expect(page.getByLabel(/Pedir confirmación de asistencia/)).toBeChecked()
  await page.getByRole('button', { name: 'Agendar cita', exact: true }).click()
  await expect(page).toHaveURL(/\/agenda\?dia=/, { timeout: 45_000 })
  await page.waitForLoadState('networkidle').catch(() => {})
  await page.waitForTimeout(3000)
  await page.getByText(nombre.split(' ')[0]).first().click()
  const dlg = page.getByRole('dialog').last()
  const folio = (await dlg.getByRole('heading').first().innerText()).replace('Cita ', '').trim()
  await expect(dlg.getByText('Por confirmar')).toBeVisible()
  await v.narrar(page, `La cita ${folio} nace por confirmar. En el detalle, el botón Liga del paciente genera su enlace personal.`, 0)
  await dlg.getByRole('button', { name: /Liga del paciente/ }).click()
  const ligaEl = dlg.locator('div', { hasText: /\/cita\/[0-9a-f]{20,}/ }).last()
  await expect(ligaEl).toBeVisible({ timeout: 30_000 })
  const liga = (await dlg.getByText(/\/cita\/[0-9a-f]{20,}/).first().innerText()).trim()
  expect(liga).toContain('?c=')
  await v.narrar(page, 'La liga lleva un código largo e irrepetible. Se puede copiar o enviar por WhatsApp. Sirve para una sola acción y vence a la hora de la cita. Ahora, la paciente la abre desde su teléfono, sin cuenta.', 0)

  // la paciente abre su liga
  await page.goto(liga, { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('heading', { name: 'Tu cita' })).toBeVisible({ timeout: 60_000 })
  await expect(page.getByText(folio).first()).toBeVisible()
  const estado0 = (await page.locator('tr', { hasText: 'Estado actual' }).innerText()).replace(/\s+/g, ' ')
  await v.narrar(page, `Esta es la pantalla de la paciente, sin menú y sin contraseña. Muestra el folio ${folio}, el servicio, el podólogo, la sede con su dirección, la fecha, el anticipo, y el estado actual: por confirmar. Abajo, las acciones permitidas y la política de reprogramación y cancelación.`, 0)
  await page.getByRole('button', { name: 'Confirmo mi asistencia' }).click()
  await expect(page.getByText('¡Cita confirmada!')).toBeVisible({ timeout: 30_000 })
  await page.waitForTimeout(1500)
  const ligaNueva = page.url()
  expect(ligaNueva).not.toBe(liga)
  await v.narrar(page, 'La paciente confirma su asistencia. El sistema responde que la cita quedó confirmada y ofrece agregarla a su calendario. Como cada liga sirve para una sola acción y la cita sigue viva, el sistema le entrega una liga nueva y cambia la dirección en pantalla.', 0)

  // reprogramar
  await v.narrar(page, 'Ahora la paciente se da cuenta de que ese día no puede. Pulsa Reprogramar mi cita.', 0)
  await page.getByRole('button', { name: 'Reprogramar mi cita' }).click()
  const rep = page.getByRole('dialog').last()
  await expect(rep.getByText('Cita actual:')).toBeVisible()
  await page.waitForTimeout(3500)
  const dN = new Date(fecha + 'T12:00'); dN.setDate(dN.getDate() + 1); if (dN.getDay() === 0) dN.setDate(dN.getDate() + 1)
  const fechaNueva = iso(dN)
  const tarjeta = rep.locator('div.card', { has: page.locator('div').filter({ hasText: new RegExp('^[a-záéíóú]{3}\.?, ' + dN.getDate() + ' ') }) }).first()
  const botones = tarjeta.locator('button.btn')
  expect(await botones.count()).toBeGreaterThan(3)
  const nuevo = botones.nth(2)
  const horaNueva = (await nuevo.innerText()).trim()
  const diaNuevo = largo(fechaNueva)
  await nuevo.scrollIntoViewIfNeeded()
  await v.narrar(page, `El portal muestra los horarios libres de los próximos catorce días con la misma podóloga. Elige el ${diaNuevo}, a las ${horaNueva}. Su anticipo se conserva y la reprogramación no cuesta si se avisa con tiempo.`, 0)
  await nuevo.click()
  await rep.getByRole('button', { name: 'Confirmar nuevo horario' }).click()
  await expect(page.getByText('Cita reprogramada')).toBeVisible({ timeout: 30_000 })
  await page.waitForTimeout(1500)
  const restantes = (await page.getByText(/te quedan/).first().innerText()).replace(/\s+/g, ' ')
  await v.narrar(page, `Aparece el aviso: cita reprogramada, con el nuevo horario. Y la nota inferior actualiza cuántas reprogramaciones sin costo le quedan: ${restantes.match(/te quedan \d+/)?.[0] ?? ''}.`, 0)

  // recepción lo ve
  await v.narrar(page, 'Del lado de la clínica, la agenda se actualizó sola. Se busca a la paciente en el día original.', 0)
  await page.goto(`/app/agenda?dia=${fecha}`, { waitUntil: 'domcontentloaded' })
  await page.waitForLoadState('networkidle').catch(() => {})
  await page.waitForTimeout(3500)
  await page.getByPlaceholder(/Buscar paciente/).first().pressSequentially(nombre, { delay: 50 })
  await page.waitForTimeout(2000)
  expect(await page.getByText(nombre).count()).toBe(0)
  await v.narrar(page, `En el ${largo(fecha)} la cita de ${nombre} ya no aparece: ese horario quedó libre para otro paciente.`, 0)
  await page.goto(`/app/agenda?dia=${fechaNueva}`, { waitUntil: 'domcontentloaded' })
  await page.waitForLoadState('networkidle').catch(() => {})
  await page.waitForTimeout(3500)
  const citaNueva = page.getByText(nombre.split(' ')[0]).first()
  await expect(citaNueva).toBeVisible({ timeout: 45_000 })
  await citaNueva.click()
  const dlgR = page.getByRole('dialog').last()
  await expect(dlgR.getByText(`Cita ${folio}`).or(dlgR.getByRole('heading').first())).toBeVisible()
  const reprog = (await dlgR.locator('tr', { hasText: 'Reprogramaciones' }).innerText()).replace(/s+/g, ' ')
  const estadoR = (await dlgR.locator('.bd, span').filter({ hasText: /^(Confirmada|Por confirmar)$/ }).first().innerText()).trim()
  await v.narrar(page, `En el ${largo(fechaNueva)} sí está: la cita ${folio}, a las ${horaNueva}, con estado ${estadoR.toLowerCase()}, y el detalle registra ${reprog.toLowerCase()}. Todo sin que recepción tuviera que intervenir.`, 0)
  await dlgR.getByRole('button', { name: 'Cerrar' }).click()

  // ───────── Parte B: sala de videoconsulta ─────────
  await v.narrar(page, 'Segunda parte: una videoconsulta. La cita es de tipo videoconsulta, para el servicio seguimiento a distancia.', 0)
  await page.goto('/app/agenda/nueva', { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('heading', { name: 'Datos de la cita' })).toBeVisible({ timeout: 30_000 })
  const ahoraMx = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Mexico_City', year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hour12: false }).formatToParts(new Date())
  const g = (t: string) => ahoraMx.find(p => p.type === t)!.value
  const hoyMx = `${g('year')}-${g('month')}-${g('day')}`
  const base = Number(g('hour')) * 60 + Number(g('minute')) + 12
  const horaVc = `${String(Math.floor(base / 60) % 24).padStart(2, '0')}:${String(base % 60).padStart(2, '0')}`
  await page.getByPlaceholder(/Buscar paciente/).pressSequentially('dani', { delay: 120 })
  const op = page.locator('button', { hasText: /· .*·/ }).filter({ has: page.locator('b') }).first()
  await expect(op).toBeVisible({ timeout: 30_000 })
  const nombreVc = (await op.locator('b').innerText()).trim()
  await op.click()
  await page.getByLabel('Servicio', { exact: true }).selectOption({ label: 'Seguimiento a distancia · 20 min' })
  const pod = page.getByLabel('Podólogo', { exact: true })
  const ops = await pod.locator('option').allInnerTexts()
  await pod.selectOption({ index: ops.findIndex((t: string, i: number) => i > 0 && /Paulina Soto/.test(t)) })
  await page.getByLabel('Videoconsulta').check()
  await page.getByLabel('Fecha', { exact: true }).fill(hoyMx)
  await page.getByLabel('Hora de inicio').fill(horaVc)
  await page.waitForTimeout(1500)
  await v.narrar(page, `Se agenda a ${nombreVc}, con la podóloga Paulina Soto, el día de hoy a las ${horaVc}, con tipo de atención videoconsulta.`, 0)
  await page.getByRole('button', { name: 'Agendar cita', exact: true }).click()
  await expect(page).toHaveURL(/\/agenda\?dia=/, { timeout: 45_000 })
  await page.waitForLoadState('networkidle').catch(() => {})
  await page.waitForTimeout(3000)
  await page.getByText(nombreVc.split(' ')[0]).first().click()
  const dlg2 = page.getByRole('dialog').last()
  const folioVc = (await dlg2.getByRole('heading').first().innerText()).replace('Cita ', '').trim()
  await v.narrar(page, `La cita ${folioVc} queda en la agenda. Para crear la sala se abre el expediente de la paciente: en su próxima cita aparece el enlace Abrir sala de videoconsulta.`, 0)
  await dlg2.getByRole('button', { name: /^Paciente$/ }).click()
  await expect(page).toHaveURL(/\/pacientes\//, { timeout: 30_000 })
  await page.waitForTimeout(3500)
  await page.getByRole('link', { name: 'Abrir sala de videoconsulta' }).first().click()
  await expect(page.getByRole('heading', { name: 'Videoconsulta' })).toBeVisible({ timeout: 30_000 })
  const urlVc = page.url()
  await page.waitForTimeout(2500)
  await v.narrar(page, 'La pantalla de videoconsulta avisa que el proveedor de video todavía no está conectado: es una versión simulada. Muestra el estado de la sala, si el paciente está conectado y si firmó el consentimiento a distancia.', 0)
  await page.getByRole('button', { name: /Crear sala y liga para el paciente/ }).click()
  const campo = page.locator('input[readonly]').first()
  await expect(campo).toBeVisible({ timeout: 30_000 })
  const ligaSala = await campo.inputValue()
  expect(ligaSala).toContain('/sala/')
  await v.narrar(page, 'Se crea la sala y el sistema entrega la liga de la paciente, una sola vez. Se puede enviar por WhatsApp o correo. La sala abre diez minutos antes de la cita.', 0)

  // la paciente entra
  await page.goto(ligaSala, { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('heading', { name: /Sala de espera de tu videoconsulta/ })).toBeVisible({ timeout: 60_000 })
  await page.waitForTimeout(2500)
  const etq = (await page.locator('[role=status]').first().innerText()).replace(/\s+/g, ' ')
  await v.narrar(page, `Esta es la sala de espera de la paciente. Arriba, el estado: ${etq}. Con una cuenta regresiva hacia la hora de la cita.`, 0)
  await page.getByRole('button', { name: 'Probar cámara y micrófono' }).click()
  await expect(page.getByText(/Cámara OK/)).toBeVisible({ timeout: 20_000 })
  await v.narrar(page, 'Antes de entrar, la paciente prueba su cámara y su micrófono. El video de esta prueba es simulado por el navegador; no hay un proveedor de videollamadas conectado.', 0)
  await v.narrar(page, 'Para entrar debe leer el consentimiento de telemedicina, aceptarlo junto con el aviso de privacidad y firmar con su nombre completo. Sin consentimiento firmado no se puede entrar.', 0)
  await expect(page.getByRole('button', { name: /Unirme a la videoconsulta/ })).toBeDisabled()
  await page.getByLabel(/He leído y acepto el consentimiento/).check()
  await page.getByLabel(/Acepto el/).check()
  await page.getByLabel(/Tu nombre completo/).pressSequentially(nombreVc, { delay: 60 })
  await page.getByRole('button', { name: /Unirme a la videoconsulta/ }).click()
  await expect(page.getByText('Estás en la sala de espera')).toBeVisible({ timeout: 30_000 })
  await page.waitForTimeout(2000)
  await v.narrar(page, 'Al firmar, la paciente pasa a la sala de espera. La pantalla aclara que el proveedor de video aún no está conectado en esta versión y que la clínica la contactará por la vía acordada.', 0)

  // la clínica la ve
  await page.goto(urlVc, { waitUntil: 'domcontentloaded' })
  await expect(page.getByText('Paciente en sala de espera')).toBeVisible({ timeout: 45_000 })
  await page.waitForTimeout(2500)
  await v.narrar(page, 'De vuelta en la pantalla de videoconsulta de la clínica: el estado de la sala cambió a paciente en sala de espera, el paciente aparece conectado, y el consentimiento a distancia ya está firmado, con su fecha, hora y dispositivo.', 0)
  await v.narrar(page, 'Hasta aquí llega lo que existe. NO CORREGIDO, requiere liberación: no hay un proveedor de videollamadas conectado, así que la consulta en vivo no se puede realizar todavía desde el sistema; la clínica debe contactar a la paciente por la vía acordada. Además, la telemedicina está apagada por defecto hasta que un abogado revise el consentimiento, y para esta prueba se activó en el ambiente de QA. Fin del caso.')
  await v.terminar(page, { folio, fecha, hora, liga: liga.replace(/[0-9a-f]{40,}/, '…'), estado0, horaNueva, diaNuevo, restantes, fechaNueva, reprog, estadoR, folioVc, horaVc, ligaSala: ligaSala.replace(/[0-9a-f]{40,}/, '…') })
})
