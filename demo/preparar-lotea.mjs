// Prepara (sin grabar) la cita de hoy en Chalco para Podólogo Prueba y la paciente process.argv[3] ?? 'CHA-EXP-000004'.
import { chromium } from '@playwright/test'
const b = await chromium.launch({ channel: 'chrome', headless: true })
const p = await b.newPage({ viewport: { width: 1366, height: 768 } })
await p.goto('http://localhost:5174/app/login', { timeout: 150000, waitUntil: 'domcontentloaded' })
await p.locator('#pf-email').waitFor({ timeout: 150000 })
await p.locator('#pf-email').fill('r@g.com'); await p.locator('#pf-pass').fill('123456')
await p.getByRole('button', { name: 'Iniciar sesión' }).click()
await p.locator('header').waitFor({ timeout: 90000 }); await p.waitForTimeout(2500)
await p.locator('header select').selectOption({ label: 'Chalco' }); await p.waitForTimeout(1500)
await p.goto('http://localhost:5174/app/agenda/nueva'); await p.waitForTimeout(5000)
await p.getByPlaceholder(/Buscar paciente/).pressSequentially(process.argv[3] ?? 'CHA-EXP-000004', { delay: 60 })
const op = p.locator('button', { hasText: /· .*·/ }).filter({ has: p.locator('b') }).first()
await op.waitFor({ timeout: 30000 }); console.log('pac', await op.innerText()); await op.click()
await p.getByLabel('Servicio', { exact: true }).selectOption({ label: 'Quiropodia · 30 min' })
const pod = p.getByLabel('Podólogo', { exact: true })
console.log(await pod.locator('option').allInnerTexts())
await pod.selectOption({ label: 'Podólogo Prueba' })
const hoy = new Date(Date.now() - 6 * 3600e3).toISOString().slice(0, 10)
await p.getByLabel('Fecha', { exact: true }).fill(hoy)
await p.waitForTimeout(2500)
console.log(await p.getByLabel('Hora de inicio').evaluate(e => e.outerHTML))
await p.getByLabel('Hora de inicio').fill(process.argv[2] ?? '07:30')
await p.waitForTimeout(1500)
console.log('precio', await p.getByLabel('Precio del servicio').inputValue())
console.log(await p.locator('.pagina').innerText().then(t => t.match(/Hay empalme[^\n]*|Horario bloqueado[^\n]*/)?.[0]))
const btn = p.getByRole('button', { name: 'Agendar cita' }); console.log('enabled', await btn.isEnabled())
await btn.click(); await p.waitForTimeout(5000); console.log(p.url())
await p.screenshot({ path: process.env.TEMP + '/prep.png' })
await b.close()
