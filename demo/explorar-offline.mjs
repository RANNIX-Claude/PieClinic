import { chromium } from '@playwright/test'
const b = await chromium.launch({ channel: 'chrome', headless: true })
const ctx = await b.newContext({ viewport: { width: 1366, height: 768 } })
const p = await ctx.newPage()
p.on('console', m => { if (true) console.log('CONSOLE', m.text().slice(0, 300)) })
p.on('pageerror', e => console.log('PAGEERROR', String(e).slice(0, 300)))
await p.goto('http://localhost:5174/app/login', { timeout: 150000, waitUntil: 'domcontentloaded' })
await p.locator('#pf-email').waitFor({ timeout: 150000 })
await p.locator('#pf-email').fill('r@g.com'); await p.locator('#pf-pass').fill('123456')
await p.getByRole('button', { name: 'Iniciar sesión' }).click()
await p.locator('header').waitFor({ timeout: 90000 }); await p.waitForTimeout(2500)
await p.locator('header select').selectOption({ label: 'Pie Clinic Centenario' }); await p.waitForTimeout(1500)
await p.getByRole('link', { name: /Caja y tickets/ }).first().click(); await p.waitForTimeout(9000)
await p.locator('.cj-buscar-in').waitFor()
await ctx.setOffline(true); await p.waitForTimeout(1500)
await p.locator('.cj-tile', { hasText: 'Paciente' }).click()
await p.getByPlaceholder(/Buscar paciente/).pressSequentially('mar', { delay: 80 }); await p.waitForTimeout(2000)
await p.locator('.cj-panel button', { hasText: 'CEN-EXP' }).first().click(); await p.waitForTimeout(800)
await p.locator('.cj-tile', { hasText: 'Paciente' }).click()
await p.keyboard.press('F2'); await p.locator('.cj-buscar-in').fill('quirop'); await p.waitForTimeout(1200)
await p.locator('.cj-res button', { hasText: 'Quiropodia' }).first().click(); await p.waitForTimeout(800)
await p.getByRole('button', { name: /Efectivo/ }).first().click(); await p.waitForTimeout(600)
await p.locator('.cj-billetes button', { hasText: '$1000' }).click(); await p.waitForTimeout(600)
const bc = p.getByRole('button', { name: /COBRAR E IMPRIMIR/ })
console.log('disabled?', await bc.isDisabled())
await bc.click()
await p.waitForTimeout(2500)
console.log('hecho:', await p.locator('.cj-hecho').count())
console.log('avisos:', JSON.stringify(await p.locator('[role=status]').allInnerTexts()).slice(0, 400))
await p.screenshot({ path: process.env.TEMP + '/off1.png' })
await b.close()
