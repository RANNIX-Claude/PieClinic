import { chromium } from '@playwright/test'
const b = await chromium.launch({ channel: 'chrome', headless: true })
const p = await b.newPage({ viewport: { width: 1366, height: 768 } })
p.on('response', async r => { if (/prp_agenda/.test(r.url())) console.log(r.status(), decodeURIComponent(r.url()).slice(0, 400), (await r.text()).slice(0, 300)) })
await p.goto('http://localhost:5174/app/login', { timeout: 150000, waitUntil: 'domcontentloaded' })
await p.locator('#pf-email').waitFor({ timeout: 150000 })
await p.locator('#pf-email').fill('p@g.com'); await p.locator('#pf-pass').fill('123456')
await p.getByRole('button', { name: 'Iniciar sesión' }).click()
await p.locator('header').waitFor({ timeout: 90000 }); await p.waitForTimeout(3000)
await p.goto('http://localhost:5174/app/consultas/nueva'); await p.waitForTimeout(3000)
await p.getByPlaceholder(/Nombre, N.º de expediente/).pressSequentially('CHA-EXP-000038', { delay: 50 })
await p.locator('button', { hasText: 'CHA-EXP-000038' }).first().click(); await p.waitForTimeout(5000)
console.log(await p.getByLabel('Cita vinculada').locator('option').allInnerTexts())
await b.close()
