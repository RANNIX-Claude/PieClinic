import { chromium } from '@playwright/test'
const b = await chromium.launch({ channel: 'chrome', headless: true })
const p = await b.newPage({ viewport: { width: 1366, height: 768 } })
p.setDefaultTimeout(90000)
await p.goto('http://localhost:5174/app/login', { waitUntil: 'domcontentloaded', timeout: 150000 })
await p.locator('#pf-email').fill('m@g.com'); await p.locator('#pf-pass').fill('123456')
await p.getByRole('button', { name: 'Iniciar sesión' }).click()
await p.locator('header').waitFor(); await p.waitForTimeout(2500)
await p.goto('http://localhost:5174/app/rh'); await p.getByRole('tab', { name: 'Incidencias', exact: true }).click(); await p.waitForTimeout(3000)
await p.getByRole('button', { name: /Nueva incidencia/ }).click()
const d = p.getByRole('dialog').last()
const ops = await d.getByLabel('Empleado').locator('option').allInnerTexts()
await d.getByLabel('Empleado').selectOption({ label: ops.find(o => o.includes('Marta Gil')) })
const t = await d.getByLabel('Tipo').locator('option').allInnerTexts()
await d.getByLabel('Tipo').selectOption({ label: t.find(o => /Retardo/.test(o)) })
await d.getByLabel('Motivo').fill('Prueba de cierre del modal (QA video E)')
p.on('console', m => console.log('CONSOLE', m.type(), m.text().slice(0, 200)))
await d.getByRole('button', { name: 'Guardar' }).click()
for (const ms of [500, 2000, 5000, 10000]) { await p.waitForTimeout(ms); console.log(ms, 'dialogos visibles:', await p.getByRole('dialog').count(), '| toasts:', (await p.locator('[role=status]').allInnerTexts()).join(' / ')) }
await b.close()
