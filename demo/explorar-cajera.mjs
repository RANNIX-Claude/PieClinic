import { chromium } from '@playwright/test'
const b = await chromium.launch({ channel: 'chrome', headless: true })
const p = await (await b.newContext({ viewport: { width: 1366, height: 768 } })).newPage()
await p.goto('http://localhost:5174/app/login', { timeout: 150000, waitUntil: 'domcontentloaded' })
await p.locator('#pf-email').waitFor({ timeout: 150000 })
await p.locator('#pf-email').fill('r@g.com'); await p.locator('#pf-pass').fill('123456')
await p.getByRole('button', { name: 'Iniciar sesión' }).click()
await p.locator('header').waitFor({ timeout: 90000 }); await p.waitForTimeout(2500)
await p.locator('header select').selectOption({ label: 'Pie Clinic Centenario' }); await p.waitForTimeout(1500)
console.log('MENU:', (await p.locator('nav a').allInnerTexts()).map(t => t.trim()).filter(Boolean).join(' | '))
await p.getByRole('link', { name: /Caja y tickets/ }).first().click(); await p.waitForTimeout(6000)
await p.locator('.cj-buscar-in').waitFor({ timeout: 60000 }).catch(() => {})
await p.screenshot({ path: process.env.TEMP + '/cajera1.png' })
await p.locator('.cj-tile', { hasText: 'Paciente' }).click().catch(() => {}); await p.waitForTimeout(1500)
await p.screenshot({ path: process.env.TEMP + '/cajera2.png' })
console.log('PANTALLA:', (await p.locator('main, .pagina').first().innerText()).replace(/\n+/g, ' | ').slice(0, 700))
await b.close()
