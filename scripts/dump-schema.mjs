// Vuelca el esquema de un ambiente a un SQL idempotente, por introspección (sin pg_dump ni Docker).
//
//   node scripts/dump-schema.mjs qa                      → supabase/bootstrap/schema.sql
//   node scripts/dump-schema.mjs prod --salida=otro.sql
//
// Esquemas: variable DUMP_SCHEMAS (default "piefirme,piefirme_app"), separados por coma.
// Cubre: extensiones, enums, secuencias, tablas, PK/UNIQUE/CHECK, FK, índices, vistas (en orden de
// dependencia, con security_invoker), funciones propias, triggers, RLS y políticas.
import fs from "fs";
import path from "path";
import { ROOT, ambiente, conectar, posicionales } from "./lib/env.mjs";

const amb = posicionales()[0] || "prod";
const cfg = ambiente(amb);
const SCHEMAS = (cfg.env.DUMP_SCHEMAS || "piefirme,piefirme_app").split(",").map((s) => s.trim());
const salida = process.argv.find((a) => a.startsWith("--salida="))?.slice(9) ?? path.join(ROOT, "supabase", "bootstrap", "schema.sql");

const client = await conectar(cfg, { soloLectura: true });
const q = (sql, p) => client.query(sql, p).then((r) => r.rows);
const out = [];
const seccion = (t) => out.push(`\n-- ============================================================\n-- ${t}\n-- ============================================================\n`);
const n = { t: 0, v: 0, f: 0, tr: 0, p: 0 };

seccion("EXTENSIONES");
for (const e of await q(`select extname from pg_extension where extname not in ('plpgsql') order by 1`)) out.push(`CREATE EXTENSION IF NOT EXISTS "${e.extname}" WITH SCHEMA extensions;`);

for (const S of SCHEMAS) {
  seccion(`ESQUEMA "${S}"`);
  out.push(`CREATE SCHEMA IF NOT EXISTS "${S}";`);

  for (const en of await q(`select t.typname, array_agg(e.enumlabel order by e.enumsortorder) labels from pg_type t join pg_enum e on e.enumtypid=t.oid join pg_namespace n on n.oid=t.typnamespace where n.nspname=$1 group by t.typname order by 1`, [S])) {
    out.push(`DO $$ BEGIN\n  CREATE TYPE "${S}"."${en.typname}" AS ENUM (${en.labels.map((l) => `'${l.replace(/'/g, "''")}'`).join(", ")});\nEXCEPTION WHEN duplicate_object THEN NULL; END $$;`);
  }
  for (const s of await q(`select c.relname from pg_class c join pg_namespace n on n.oid=c.relnamespace where c.relkind='S' and n.nspname=$1 order by 1`, [S])) out.push(`CREATE SEQUENCE IF NOT EXISTS "${S}"."${s.relname}";`);

  const tablas = await q(`select c.relname from pg_class c join pg_namespace n on n.oid=c.relnamespace where c.relkind in ('r','p') and n.nspname=$1 and c.relname <> '_rannix_migraciones' order by 1`, [S]);
  n.t += tablas.length;
  for (const t of tablas) {
    const cols = await q(`select a.attname name, format_type(a.atttypid,a.atttypmod) type, a.attnotnull notnull, pg_get_expr(ad.adbin,ad.adrelid) def, a.attidentity ident, a.attgenerated gen
      from pg_attribute a left join pg_attrdef ad on ad.adrelid=a.attrelid and ad.adnum=a.attnum
      where a.attrelid=($1||'.'||quote_ident($2))::regclass and a.attnum>0 and not a.attisdropped order by a.attnum`, [`"${S}"`, t.relname]);
    const defs = cols.map((c) => {
      let d = `  "${c.name}" ${c.type}`;
      if (c.gen === "s") d += ` GENERATED ALWAYS AS (${c.def}) STORED`;
      else if (c.ident === "d") d += " GENERATED BY DEFAULT AS IDENTITY";
      else if (c.ident === "a") d += " GENERATED ALWAYS AS IDENTITY";
      else if (c.def) d += ` DEFAULT ${c.def}`;
      return d + (c.notnull ? " NOT NULL" : "");
    });
    out.push(`CREATE TABLE IF NOT EXISTS "${S}"."${t.relname}" (\n${defs.join(",\n")}\n);`);
  }
  for (const so of await q(`select s.relname seq, t.relname tbl, a.attname col from pg_class s join pg_depend d on d.objid=s.oid and d.deptype='a' join pg_class t on t.oid=d.refobjid join pg_attribute a on a.attrelid=t.oid and a.attnum=d.refobjsubid join pg_namespace n on n.oid=s.relnamespace where s.relkind='S' and n.nspname=$1`, [S]))
    out.push(`ALTER SEQUENCE "${S}"."${so.seq}" OWNED BY "${S}"."${so.tbl}"."${so.col}";`);

  const cons = await q(`select conname, conrelid::regclass::text tbl, contype, pg_get_constraintdef(oid) def from pg_constraint where connamespace=(select oid from pg_namespace where nspname=$1) and contype in ('p','u','c','f') and conrelid::regclass::text not like '%_rannix_migraciones' order by (contype='f'), contype, conname`, [S]);
  for (const k of cons) out.push(`DO $rx$ BEGIN ALTER TABLE ${k.tbl} ADD CONSTRAINT "${k.conname}" ${k.def}; EXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL; END $rx$;`);
  const nombresCons = new Set(cons.map((k) => k.conname));
  for (const i of await q(`select indexname, indexdef from pg_indexes where schemaname=$1 and tablename <> '_rannix_migraciones' order by 1`, [S]))
    if (!nombresCons.has(i.indexname)) out.push(i.indexdef.replace(/^CREATE (UNIQUE )?INDEX /, "CREATE $1INDEX IF NOT EXISTS ") + ";");
}

seccion("VISTAS (en orden de dependencia)");
{
  const vs = await q(`select c.oid, n.nspname s, c.relname v, pg_get_viewdef(c.oid,true) def, coalesce(c.reloptions::text,'') opts from pg_class c join pg_namespace n on n.oid=c.relnamespace where c.relkind='v' and n.nspname = any($1) order by 1`, [SCHEMAS]);
  n.v = vs.length;
  const porOid = new Map(vs.map((v) => [v.oid, v]));
  const deps = new Map();
  for (const r of await q(`select distinct r.ev_class vista, d.refobjid dep from pg_rewrite r join pg_depend d on d.objid=r.oid join pg_class dc on dc.oid=d.refobjid where dc.relkind='v' and r.ev_class <> d.refobjid`)) {
    if (!porOid.has(r.vista) || !porOid.has(r.dep)) continue;
    (deps.get(r.vista) ?? deps.set(r.vista, new Set()).get(r.vista)).add(r.dep);
  }
  const vistos = new Set(), orden = [];
  const visita = (o, pila = new Set()) => { if (vistos.has(o) || pila.has(o)) return; pila.add(o); for (const d of deps.get(o) ?? []) visita(d, pila); pila.delete(o); vistos.add(o); orden.push(o); };
  for (const v of vs) visita(v.oid);
  for (const o of orden) {
    const v = porOid.get(o);
    out.push(`CREATE OR REPLACE VIEW "${v.s}"."${v.v}" AS\n${v.def.trim().replace(/;$/, "")};`);
    if (/security_invoker=(true|on)/.test(v.opts)) out.push(`ALTER VIEW "${v.s}"."${v.v}" SET (security_invoker = true);`);
  }
}

seccion("FUNCIONES");
for (const S of SCHEMAS) {
  const fs_ = await q(`select pg_get_functiondef(p.oid) def from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname=$1 and p.prokind='f' and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e') order by p.proname`, [S]);
  n.f += fs_.length; for (const f of fs_) out.push(f.def + ";");
}

seccion("TRIGGERS");
for (const S of SCHEMAS)
  for (const t of await q(`select tgname, pg_get_triggerdef(t.oid) def, c.relname tbl from pg_trigger t join pg_class c on c.oid=t.tgrelid join pg_namespace n on n.oid=c.relnamespace where n.nspname=$1 and not t.tgisinternal order by 1`, [S])) {
    n.tr++; out.push(`DROP TRIGGER IF EXISTS "${t.tgname}" ON "${S}"."${t.tbl}";\n${t.def};`);
  }

seccion("RLS Y POLÍTICAS");
for (const S of SCHEMAS) {
  for (const r of await q(`select c.relname, c.relforcerowsecurity forced from pg_class c join pg_namespace n on n.oid=c.relnamespace where c.relkind in ('r','p') and n.nspname=$1 and c.relrowsecurity order by 1`, [S])) {
    out.push(`ALTER TABLE "${S}"."${r.relname}" ENABLE ROW LEVEL SECURITY;`);
    if (r.forced) out.push(`ALTER TABLE "${S}"."${r.relname}" FORCE ROW LEVEL SECURITY;`);
  }
  for (const p of await q(`select tablename, policyname, permissive, roles::text roles, cmd, qual, with_check from pg_policies where schemaname=$1 order by 1,2`, [S])) {
    n.p++;
    const roles = p.roles.replace(/^\{|\}$/g, "") || "public";
    out.push(`DROP POLICY IF EXISTS "${p.policyname}" ON "${S}"."${p.tablename}";`);
    out.push(`CREATE POLICY "${p.policyname}" ON "${S}"."${p.tablename}" AS ${p.permissive} FOR ${p.cmd} TO ${roles}${p.qual ? ` USING (${p.qual})` : ""}${p.with_check ? ` WITH CHECK (${p.with_check})` : ""};`);
  }
}
await client.end();

fs.mkdirSync(path.dirname(salida), { recursive: true });
fs.writeFileSync(salida, `-- Volcado de esquema (${amb}) — esquemas: ${SCHEMAS.join(", ")} — ${new Date().toISOString()}\n-- Por introspección de pg_catalog. Idempotente. Los grants NO van aquí: los copia clonar-ambiente.mjs.\n` + out.join("\n") + "\n");
console.log(`Escrito ${path.relative(ROOT, salida)} — tablas ${n.t}, vistas ${n.v}, funciones ${n.f}, triggers ${n.tr}, políticas ${n.p}`);
